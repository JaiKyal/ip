-- V1: core schema for the Shopping Cart & Order Management System.
-- Money is NUMERIC(12,2). Timestamps are TIMESTAMPTZ. Ids are identity columns.
-- Status values are checked here as well as in Java, so bad data cannot get in either way.

-- ---------------------------------------------------------------- users
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(120) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,           -- BCrypt hash, never the password
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT users_role_check CHECK (role IN ('CUSTOMER', 'ADMIN'))
);
-- Emails are unique ignoring case: Jai@x.com and jai@x.com are the same person.
CREATE UNIQUE INDEX users_email_lower_uq ON users (lower(email));

-- ----------------------------------------------------------- categories
CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80) NOT NULL,
    description TEXT,
    CONSTRAINT categories_name_uq UNIQUE (name)
);

-- ------------------------------------------------------------- products
CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(200)  NOT NULL,
    description    TEXT          NOT NULL DEFAULT '',
    price          NUMERIC(12,2) NOT NULL,
    stock_quantity INTEGER       NOT NULL DEFAULT 0,
    image_url      VARCHAR(500),
    active         BOOLEAN       NOT NULL DEFAULT TRUE,   -- soft delete: inactive products stay for order history
    category_id    BIGINT        NOT NULL REFERENCES categories (id),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT products_price_check CHECK (price >= 0),
    -- The database itself refuses to oversell, even if application code has a bug.
    CONSTRAINT products_stock_check CHECK (stock_quantity >= 0)
);
CREATE INDEX products_category_idx ON products (category_id);
CREATE INDEX products_active_name_idx ON products (active, lower(name));

-- ---------------------------------------------------------------- carts
CREATE TABLE carts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT carts_user_uq UNIQUE (user_id)               -- one cart per user
);

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    BIGINT  NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    product_id BIGINT  NOT NULL REFERENCES products (id),
    quantity   INTEGER NOT NULL,
    CONSTRAINT cart_items_quantity_check CHECK (quantity > 0),
    CONSTRAINT cart_items_cart_product_uq UNIQUE (cart_id, product_id)   -- same product = one line
);
CREATE INDEX cart_items_product_idx ON cart_items (product_id);

-- --------------------------------------------------------------- orders
CREATE TABLE orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number    VARCHAR(30)   NOT NULL,
    user_id         BIGINT        NOT NULL REFERENCES users (id),
    status          VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    subtotal        NUMERIC(12,2) NOT NULL,
    total_amount    NUMERIC(12,2) NOT NULL,
    payment_status  VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    payment_method  VARCHAR(30)   NOT NULL,
    -- Sent by the browser with each checkout; a repeated key means a double submit.
    idempotency_key VARCHAR(64),
    order_date      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT orders_number_uq UNIQUE (order_number),
    CONSTRAINT orders_user_idempotency_uq UNIQUE (user_id, idempotency_key),
    CONSTRAINT orders_status_check CHECK (status IN
        ('PENDING', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT orders_payment_status_check CHECK (payment_status IN
        ('PENDING', 'PAID', 'FAILED', 'REFUNDED')),
    CONSTRAINT orders_amounts_check CHECK (subtotal >= 0 AND total_amount >= 0)
);
CREATE INDEX orders_user_idx ON orders (user_id, order_date DESC);
CREATE INDEX orders_status_idx ON orders (status);
CREATE INDEX orders_date_idx ON orders (order_date DESC);

-- ---------------------------------------------------------- order_items
-- name and unit_price are copied at purchase time so old orders never change
-- when the product is edited later.
CREATE TABLE order_items (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id            BIGINT        NOT NULL REFERENCES products (id),   -- RESTRICT: sold products cannot be hard-deleted
    product_name_snapshot VARCHAR(200)  NOT NULL,
    quantity              INTEGER       NOT NULL,
    unit_price            NUMERIC(12,2) NOT NULL,
    line_total            NUMERIC(12,2) NOT NULL,
    CONSTRAINT order_items_quantity_check CHECK (quantity > 0),
    CONSTRAINT order_items_price_check CHECK (unit_price >= 0),
    CONSTRAINT order_items_line_total_check CHECK (line_total = unit_price * quantity)
);
CREATE INDEX order_items_order_idx ON order_items (order_id);
CREATE INDEX order_items_product_idx ON order_items (product_id);

-- ------------------------------------------------------------- payments
-- SIMULATED payments only. No card numbers, CVVs or other payment credentials are ever stored.
CREATE TABLE payments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              BIGINT        NOT NULL REFERENCES orders (id),
    payment_method        VARCHAR(30)   NOT NULL,
    payment_status        VARCHAR(20)   NOT NULL,
    amount                NUMERIC(12,2) NOT NULL,
    transaction_reference VARCHAR(64)   NOT NULL,
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT payments_reference_uq UNIQUE (transaction_reference),
    CONSTRAINT payments_status_check CHECK (payment_status IN ('PAID', 'FAILED', 'REFUNDED')),
    CONSTRAINT payments_amount_check CHECK (amount >= 0)
);
CREATE INDEX payments_order_idx ON payments (order_id);
